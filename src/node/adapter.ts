import { checkOutDir, relativePath } from "../adapter/paths";
import { type Adapter, NODE_LIKE_CAPABILITIES } from "../adapter/types";

/**
 * The Node layout: a `server.mjs` that runs the server bundle with {@link serve} from
 * `@shadow-js/dusk/node`, serving the client folder first. It is the adapter of the Node runtime and
 * the layout Tarout runs. It reads `PORT` (default 3000) and `HOST` (default `0.0.0.0`) from the
 * environment, so the same file works in a container and behind a platform's router. `DUSK_WORKERS` (a number or `auto`) runs
 * that many server processes that share the port (see `serve`'s `workers` option); without it the server is one process.
 *
 * @packageDocumentation
 */

/**
 * The port and host the Node layout listens on when `PORT` and `HOST` are not set. The generated `server.mjs` and
 * `dusk start` (the CLI) both read these, so the two cannot drift apart.
 * @internal
 */
export const NODE_DEFAULT_PORT = 3000;
/** @internal */
export const NODE_DEFAULT_HOST = "0.0.0.0";

/** Options of the {@link node} adapter. @since 1.0.0 */
export interface NodeAdapterOptions {
  /** Output folder relative to the project. Default `dist/node`. */
  readonly outDir?: string;
}

/**
 * The adapter for Node.js: writes `server.mjs`. Run it with `node dist/node/server.mjs` after
 * `vite build`; the packages the server needs at run time are `@shadow-js/dusk` and its peers.
 *
 * @param options See {@link NodeAdapterOptions}.
 * @returns The adapter for `dusk({ adapter })`.
 * @throws TypeError for an invalid `outDir`.
 * @example
 * import { node } from "@shadow-js/dusk/node";
 * export default { plugins: [dusk({ adapter: node() })] };
 * @since 1.0.0
 */
export function node(options: NodeAdapterOptions = {}): Adapter {
  return nodeLayout({ name: "node", outDir: checkOutDir("node()", options.outDir ?? "dist/node") });
}

/**
 * The shared Node layout. Exported to the platform adapters that run the same way (Tarout).
 * @param input The adapter name, the checked output folder and an optional comment for the file.
 * @returns The adapter.
 * @internal
 * @since 1.0.0
 */
export function nodeLayout(input: {
  readonly name: string;
  readonly outDir: string;
  readonly note?: string;
}): Adapter {
  return {
    name: input.name,
    outDir: input.outDir,
    env: "process",
    bundling: "dependencies",
    capabilities: {
      ...NODE_LIKE_CAPABILITIES,
      websockets: true,
      middlewareForStaticFiles: true,
      earlyHints: true,
    },
    async build(context) {
      const clientFolder = relativePath(context.outDir, context.clientDir);
      const serverFile = relativePath(context.outDir, context.serverEntry);
      const note = input.note === undefined ? "" : ` ${input.note}`;
      await context.emit(
        "server.mjs",
        [
          `// Generated by @shadow-js/dusk (adapter: ${input.name}).${note}`,
          'import { serve } from "@shadow-js/dusk/node";',
          `import { handler } from ${JSON.stringify(serverFile)};`,
          'import { fileURLToPath } from "node:url";',
          "",
          // DUSK_WORKERS=4 (or "auto") runs that many server processes that share the port.
          "const workers = process.env.DUSK_WORKERS;",
          "await serve(handler, {",
          `  port: Number(process.env.PORT ?? ${NODE_DEFAULT_PORT}),`,
          `  host: process.env.HOST ?? ${JSON.stringify(NODE_DEFAULT_HOST)},`,
          '  workers: workers === undefined || workers === "" ? undefined : workers === "auto" ? "auto" : Number(workers),',
          // Prerendered pages: `/about` answers about/index.html (or about.html for the file layout), `/` answers index.html.
          `  static: { dir: fileURLToPath(new URL(${JSON.stringify(clientFolder.endsWith("/") ? clientFolder : `${clientFolder}/`)}, import.meta.url)), index: "index.html", extensions: [".html"], assetsDir: ${JSON.stringify(context.manifest.assetsDir)}, pages: ${JSON.stringify(context.staticPages)} },`,
          "});",
          "",
        ].join("\n"),
      );
      context.log(`wrote ${input.outDir}/server.mjs (start with: node ${input.outDir}/server.mjs)`);
    },
  };
}
