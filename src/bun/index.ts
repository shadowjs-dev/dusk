/**
 * `@shadow-js/dusk/bun`: run a Dusk app on Bun's native server (`Bun.serve`), and the `bun()`
 * adapter that emits the entry for `bun dist/bun/server.mjs`.
 *
 * Static files come from the client folder with the same path rules as the Node server; responses
 * are gzipped; a stop waits for requests in flight. The handler is the one from the server bundle.
 * @packageDocumentation
 */

import {
  type NativeListen,
  type NativeServeHandle,
  type NativeServeOptions,
  startNative,
} from "../adapter/native";
import { checkOutDir, relativePath } from "../adapter/paths";
import { type Adapter, NODE_LIKE_CAPABILITIES } from "../adapter/types";
import type { BunRuntime } from "../internal/bun-sockets";
import type { Handler } from "../server/types";

export type {
  NativeServeHandle as BunServeHandle,
  NativeServeOptions as BunServeOptions,
} from "../adapter/native";

function bunGlobal(): BunRuntime {
  const bun: unknown = Reflect.get(globalThis, "Bun");
  if (typeof bun !== "object" || bun === null || typeof Reflect.get(bun, "serve") !== "function") {
    throw new Error(
      "@shadow-js/dusk/bun: this runtime is not Bun (globalThis.Bun.serve is missing).",
    );
  }
  return {
    serve(options) {
      const serve: unknown = Reflect.get(bun, "serve");
      if (typeof serve !== "function")
        throw new Error(__DEV__ ? "Bun.serve is missing" : "DUSK_BUN_1");
      const server: unknown = Reflect.apply(serve, bun, [options]);
      if (typeof server !== "object" || server === null)
        throw new Error(__DEV__ ? "Bun.serve did not return a server" : "DUSK_BUN_2");
      const port: unknown = Reflect.get(server, "port");
      const stop: unknown = Reflect.get(server, "stop");
      if (typeof port !== "number" || typeof stop !== "function")
        throw new Error(__DEV__ ? "Bun.serve returned an unexpected server" : "DUSK_BUN_2");
      return {
        port,
        stop: (closeActive: boolean) =>
          Promise.resolve(Reflect.apply(stop, server, [closeActive])).then(() => undefined),
      };
    },
  };
}

const listen: NativeListen = (hostname, port, fetch) => {
  const server = bunGlobal().serve({
    hostname,
    port,
    fetch: (request, bunServer) => fetch(request, bunServer.requestIP(request)?.address),
  });
  return {
    get port() {
      return server.port;
    },
    hostname,
    stop: (closeActive) => server.stop(closeActive),
  };
};

/**
 * Serves a handler with `Bun.serve`.
 *
 * @param handler The fetch handler, usually `handler` from the server bundle.
 * @param options Port, hostname, static folder, compression and shutdown.
 * @returns The running server.
 * @throws Error when the code does not run on Bun.
 * @example
 * import { serve } from "@shadow-js/dusk/bun";
 * import { handler } from "./dist/server/entry.js";
 * await serve(handler, { static: "/srv/app/dist/client", hostname: "0.0.0.0" });
 * @since 1.0.0
 */
export function serve(
  handler: Handler,
  options: NativeServeOptions = {},
): Promise<NativeServeHandle> {
  if (handler.upgrade === undefined) return startNative(listen, handler, options);
  return import("../internal/bun-sockets").then(({ createBunListen }) =>
    startNative(
      createBunListen(
        bunGlobal(),
        handler,
        options.onError ?? ((error: unknown) => console.error("[dusk] request failed", error)),
      ),
      handler,
      options,
    ),
  );
}

/** Options of the {@link bun} adapter. @since 1.0.0 */
export interface BunAdapterOptions {
  /** Output folder relative to the project. Default `dist/bun`. */
  readonly outDir?: string;
}

/**
 * The Bun adapter: writes `server.mjs`, which serves the server bundle and the client folder with
 * `Bun.serve`. Run it with `bun <outDir>/server.mjs`. It reads `PORT` (default 3000) and `HOST`
 * (default `0.0.0.0`).
 *
 * @param options See {@link BunAdapterOptions}.
 * @returns The adapter for `dusk({ adapter })`.
 * @throws TypeError for an invalid `outDir`.
 * @example
 * // vite.config.ts
 * import { dusk } from "@shadow-js/dusk/vite";
 * import { bun } from "@shadow-js/dusk/bun";
 * export default { plugins: [dusk({ adapter: bun() })] };
 * @since 1.0.0
 */
export function bun(options: BunAdapterOptions = {}): Adapter {
  const outDir = checkOutDir("bun()", options.outDir ?? "dist/bun");
  return {
    name: "bun",
    outDir,
    env: "process",
    bundling: "dependencies",
    // The native layer asks the handler's gate about each file (`runMiddlewareForStaticFiles`), as the Node layer does.
    capabilities: { ...NODE_LIKE_CAPABILITIES, websockets: true, middlewareForStaticFiles: true },
    async build(context) {
      const clientFolder = relativePath(context.outDir, context.clientDir);
      const serverFile = relativePath(context.outDir, context.serverEntry);
      await context.emit(
        "server.mjs",
        [
          "// Generated by @shadow-js/dusk (adapter: bun). Run with: bun server.mjs",
          'import { serve } from "@shadow-js/dusk/bun";',
          `import { handler } from ${JSON.stringify(serverFile)};`,
          'import { fileURLToPath } from "node:url";',
          "",
          "await serve(handler, {",
          '  hostname: process.env.HOST ?? "0.0.0.0",',
          `  static: fileURLToPath(new URL(${JSON.stringify(clientFolder.endsWith("/") ? clientFolder : `${clientFolder}/`)}, import.meta.url)),`,
          `  assetsDir: ${JSON.stringify(context.manifest.assetsDir)},`,
          `  prefix: ${JSON.stringify(context.manifest.base)},`,
          `  pages: ${JSON.stringify(context.staticPages)},`,
          "});",
          "",
        ].join("\n"),
      );
      context.log(`wrote ${outDir}/server.mjs`);
    },
  };
}
